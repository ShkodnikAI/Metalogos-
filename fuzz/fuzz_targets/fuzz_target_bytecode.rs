#![no_main]
use libfuzzer_sys::fuzz_target;

// ── Наряд №256: фаззинг реального пути загрузки .mbc ────────────────
//
// Произвольные байты проходят через `Program::deserialize` — тот же код,
// что и в `mlog run file.mbc` (bincode legacy + лимит размера №146).
//
// Контракт: Ok(Program) или громкий Err. НИКОГДА паника/зависание.
// Найденные паники чинятся громкими ошибками со стабильным кодом
// BYTECODE_INVALID (ADR-0131) в пути загрузки.
//
// Громкая граница (§8.4 наряда): malicious-bytecode ДЕСПЕТЧ здесь
// намеренно не исполняется — у VM нет API бюджета шагов, бесконечный
// цикл в байткоде завис бы фаззер и CI-джобу. Вернуться, когда у VM
// появится step-budget (вопрос к наряду-отчёту №256).
fuzz_target!(|data: &[u8]| {
    let _ = metalogos::bytecode::Program::deserialize(data);
});

    #[test]
    fn test_resolve_graph_version_conflict() {
        let (_dir, registry) = setup_test_registry("resolve_conflict");
        // app -> pkg_a (1.0.0) -> shared (1.0.0)
        // app -> pkg_b (1.0.0) -> shared (2.0.0)
        // conflict: shared must be both 1.0.0 and 2.0.0
        write_pkg_to_registry(&registry, "shared", "1.0.0", &[]);
        // We need shared 2.0.0 too — but registry only has one version per name.
        // For the test, we trick: pkg_b requires shared 2.0.0, but registry
        // has shared 1.0.0. resolve_graph will fail with VersionConflict
        // because the requested version (2.0.0) doesn't match the resolved
        // version (1.0.0).
        write_pkg_to_registry(&registry, "pkg_a", "1.0.0", &[("shared", "1.0.0")]);
        write_pkg_to_registry(&registry, "pkg_b", "1.0.0", &[("shared", "2.0.0")]);

        let mut deps = HashMap::new();
        deps.insert("pkg_a".to_string(), "1.0.0".to_string());
        deps.insert("pkg_b".to_string(), "1.0.0".to_string());
        let manifest = Manifest {
            package: Package::default(),
            dependencies: deps,
        };

        let err = resolve_graph(&manifest, &registry).unwrap_err();
        match err {
            ResolveError::VersionConflict { name, .. } => {
                assert_eq!(name, "shared");
            }
            other => panic!("expected VersionConflict, got: {:?}", other),
        }
    }


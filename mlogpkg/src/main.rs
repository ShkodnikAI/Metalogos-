    fn write_pkg_to_registry(registry: &Path, name: &str, version: &str, deps: &[(&str, &str)]) {
        let pkg_dir = registry.join(name);
        fs::create_dir_all(&pkg_dir).unwrap();
        let mut deps_map = HashMap::new();
        for (d, v) in deps {
            deps_map.insert(d.to_string(), v.to_string());
        }
        let manifest = Manifest {
            package: Package {
                name: name.to_string(),
                version: version.to_string(),
                edition: "2024".to_string(),
            },
            dependencies: deps_map,
        };
        let toml_str = toml::to_string_pretty(&manifest).unwrap();
        fs::write(pkg_dir.join("mlog.toml"), toml_str).unwrap();
        // Also create a minimal source file so build doesn't error.
        fs::create_dir_all(pkg_dir.join("src")).unwrap();
        fs::write(
            pkg_dir.join("src/main.mlog"),
            "entity v: String = \"\"\nflow Main { input: String = v -> output }\n",
        )
        .unwrap();
    }


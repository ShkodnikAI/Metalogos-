#!/usr/bin/env python3
"""№823 E3 — the confidence calibration of reflex_predict: ECE +
reliability diagram on held-out data NOT generated by the teacher.

The data is PROCEDURAL ground truth (a seeded linear score + logistic
noise, 2 classes, 2 features) — no LLM anywhere in the loop, so the
held-out set is clean of teacher provenance by construction (the E3
requirement). The train split (400) and the held-out split (200) come
from the same seeded generator with disjoint seeds; three independent
seeds are measured.

The .mlog program trains the Dense head (dense(8, relu), dense(2,
softmax), 200 epochs, lr 0.1 — the dispatch constants), then predicts
EVERY held-out row and prints "E3 <true_class> <argmax_label>
<confidence-of-argmax>" lines; the Python side computes the top-label
accuracy, the 10-bin equal-width reliability table and the Expected
Calibration Error (ECE = sum over bins of |acc(b) - conf(b)| * n(b) /
N).

Reproduces:
  cargo build --release -p metalogos-server --bin mlog
  python3 scripts/research/e3_calibration.py [--out CSV]
"""
import argparse
import csv
import math
import os
import re
import subprocess
import sys
import tempfile

BIN = os.environ.get("MLOG_BIN", "target/release/mlog")

PROGRAM_TMPL = """\
// №823 E3 — generated measurement program (do not hand-edit)
reflex CalHead {{
  input: embedding(2)
  layers: [dense(8, relu), dense(2, softmax)]
  labels: ["neg", "pos"]
  seed: {seed}
}}

pattern Cal(_x: String) -> String {{
  let train = [{train}]
  let heldout = [{heldout}]
  let r = reflex_train(CalHead, train, 200.0, "accuracy", 0.99)
  let mut out = "E3TRAIN loss=" + to_string(r.loss) + " acc=" + to_string(r.accuracy)
  each row in heldout {{
    let p = reflex_predict(CalHead, [row[0], row[1]])
    let conf = confidence(p)
    let label = to_string(p)
    out = out + "|E3 " + to_string(row[2]) + " " + label + " " + to_string(conf)
  }}
  return out
}}

flow Main {{ input: String = "x" -> Cal -> output }}
"""


def logistic_row(u, v, seed_state):
    """A row with PROCEDURAL ground truth: score = 3u - 2v + noise;
    class = 1 if p(score + logistic noise) > 0.5 — the noise is part of
    the truth (an imperfect but KNOWN process, not a teacher)."""
    x, y, s = seed_state
    x = (x * 1103515245 + 12345) % (2 ** 31)
    y = (y * 1103515245 + 12345) % (2 ** 31)
    s = (s * 1103515245 + 12345) % (2 ** 31)
    u = (x % 2000) / 1000.0 - 1.0
    v = (y % 2000) / 1000.0 - 1.0
    noise = ((s % 2000) / 1000.0 - 1.0) * 1.5
    score = 3.0 * u - 2.0 * v + noise
    p = 1.0 / (1.0 + math.exp(-score))
    cls = 1.0 if p > 0.5 else 0.0
    return f"[{u:.4f}, {v:.4f}, {cls}]", (u, v, cls), (x, y, s)


def gen_split(n, seed):
    rows, meta = [], []
    st = (seed, seed * 7 + 1, seed * 13 + 3)
    for _ in range(n):
        r, m, st = logistic_row(0, 0, st)
        rows.append(r)
        meta.append(m)
    return rows, meta


def build_program(seed):
    train, _ = gen_split(400, seed)
    heldout, _ = gen_split(200, seed * 101 + 7)  # disjoint seed stream
    return PROGRAM_TMPL.format(seed=seed, train=", ".join(train),
                               heldout=", ".join(heldout))


def run_once(program, tmpdir, tag):
    path = os.path.join(tmpdir, f"e3_{tag}.mlog")
    with open(path, "w") as f:
        f.write(program)
    proc = subprocess.run([BIN, "run", path], capture_output=True, text=True,
                          timeout=600)
    if proc.returncode != 0:
        raise SystemExit(f"mlog run failed rc={proc.returncode}:\n"
                         f"stdout: {proc.stdout[:300]}\nstderr: {proc.stderr[:600]}")
    m = re.search(r"E3TRAIN loss=([0-9.eE+-]+) acc=([0-9.eE+-]+)(.*)", proc.stdout)
    if not m:
        raise SystemExit(f"no E3TRAIN marker: {proc.stdout[:300]}")
    loss, acc = float(m.group(1)), float(m.group(2))
    pairs = re.findall(r"E3 ([0-9.]+) (\S+) ([0-9.eE+-]+)", m.group(3))
    return loss, acc, [(float(t), lab, float(c)) for t, lab, c in pairs]


def ece_table(pairs, bins=10):
    """(ece, [(bin_lo, bin_hi, n, mean_conf, acc)]) — the equal-width
    reliability table; ECE = Σ |acc(b) − conf(b)| · n(b) / N."""
    buckets = [[] for _ in range(bins)]
    for truth, label, conf in pairs:
        correct = 1.0 if (label == "pos") == (truth == 1.0) else 0.0
        b = min(int(conf * bins), bins - 1)
        buckets[b].append((conf, correct))
    table, ece = [], 0.0
    total = sum(len(b) for b in buckets)
    for i, b in enumerate(buckets):
        lo, hi = i / bins, (i + 1) / bins
        n = len(b)
        mean_conf = sum(c for c, _ in b) / n if n else 0.0
        acc = sum(k for _, k in b) / n if n else 0.0
        table.append((lo, hi, n, mean_conf, acc))
        if n:
            ece += abs(acc - mean_conf) * n / total
    return ece, table


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--out", default="docs/research/e3_calibration.csv")
    args = ap.parse_args()

    if not os.path.exists(BIN):
        raise SystemExit(f"{BIN} not found — build the release binary first")

    rows = []
    with tempfile.TemporaryDirectory() as td:
        for seed in range(1, args.seeds + 1):
            loss, acc, pairs = run_once(build_program(seed), td, f"s{seed}")
            top_acc = sum(1 for t, lab, _ in pairs
                          if (lab == "pos") == (t == 1.0)) / len(pairs)
            ece, table = ece_table(pairs)
            print(f"\nseed {seed}: train loss={loss:.4f} acc={acc:.3f}; "
                  f"held-out top-label acc={top_acc:.3f}; "
                  f"ECE={ece:.4f} (N={len(pairs)})")
            print("  bin        n   mean_conf   acc")
            for lo, hi, n, mc, a in table:
                bar = "#" * int(a * 30)
                print(f"  {lo:.1f}-{hi:.1f}  {n:4d}   {mc:.3f}     {a:.3f} {bar}")
            for lo, hi, n, mc, a in table:
                rows.append({"seed": seed, "bin_lo": lo, "bin_hi": hi,
                             "n": n, "mean_conf": round(mc, 4),
                             "acc": round(a, 4), "ece": round(ece, 4),
                             "heldout_top_acc": round(top_acc, 4),
                             "train_loss": loss, "train_acc": acc})
            # the raw (truth, label, confidence) stream
            raw_path = f"docs/research/e3_calibration_seed{seed}_raw.csv"
            with open(raw_path, "w", newline="") as f:
                w = csv.writer(f)
                w.writerow(["truth", "argmax_label", "confidence", "correct"])
                for t, lab, c in pairs:
                    w.writerow([t, lab, c,
                                int((lab == "pos") == (t == 1.0))])
            print(f"  raw stream: {raw_path}")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"\nCSV written: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

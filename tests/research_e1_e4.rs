// ── the fixture (recorded verbatim in the artifacts) ────────────────

/// The master seed — recorded in every artifact (the №987 form).
const SEED: u64 = 20_261_121;
const CORPUS_ROWS: usize = 400;
const CLASSES: [&str; 4] = ["alpha", "beta", "gamma", "delta"];
const TEMPLATE_WORDS: [&str; 8] = [
    "yields", "blocks", "replays", "prints", "guards", "merges", "scans", "seals",
];

/// A fixed 64-bit LCG (the Knuth MMIX constants). The corpus generator
/// is version-independent BY CONSTRUCTION: no dependency RNG is touched,
/// so a `rand` patch-bump cannot move the fixture (the №987 lesson).
struct Lcg(u64);
impl Lcg {
    fn next_u64(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next_u64() % n as u64) as usize
    }
}


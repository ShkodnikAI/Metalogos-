//! №988 (E1–E4, ADR-0200 §5) — the measurement harness for the four
//! roadmap experiments: E1 embed speed, E2 reflex_train time, E3
//! confidence calibration, E4 teacher baseline_agreement.
//!
//! The tests are ENV-GUARDED: without `METALOGOS_RESEARCH_E1E4=1` each
//! one passes as a loud no-op (measurements are not assertions; CI
//! stays untouched and prints the skip line). The documented invocation
//! is `scripts/research/run_e1_e4.sh`, which sets the env, runs this
//! target in release mode with one thread, captures the JSON document
//! printed between the markers, and writes the machine-readable
//! artifacts next to the research reports in `docs/research/`.
//!
//! №987 lesson applied: the corpus is generated by a fixed 64-bit LCG
//! whose constants live BELOW in this file — the seed is fixed in the
//! RESULT RECORD, and no test pins a dependency's RNG sequence.
//! Behavior is untouched: this file adds no product code path.

